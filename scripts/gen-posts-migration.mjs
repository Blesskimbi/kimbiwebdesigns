/**
 * Generates the SQL that creates the posts table and loads the existing
 * posts/*.md files into it.
 *
 * Writes to supabase/migrations/create_posts_table.sql, which is then pasted
 * into the Supabase SQL editor. Going through generated SQL rather than an API
 * script means the migration needs no service-role key and can be read in full
 * before it runs.
 *
 * Slugs and dates are carried across verbatim — those are the URLs Google has
 * already indexed, and changing one throws away its ranking.
 *
 * Usage: node scripts/gen-posts-migration.mjs
 */
import matter from "gray-matter";
import { readFileSync, writeFileSync, readdirSync } from "fs";
import { join, resolve } from "path";
import { fileURLToPath } from "url";

const __dirname = fileURLToPath(new URL(".", import.meta.url));
const rootDir = resolve(__dirname, "..");
const postsDir = join(rootDir, "posts");
const outFile = join(rootDir, "supabase", "migrations", "create_posts_table.sql");

/** Postgres dollar-quoting: safe for markdown full of quotes, backslashes and $. */
function q(value) {
  if (value === null || value === undefined || value === "") return "NULL";
  const text = String(value);
  let tag = "md";
  while (text.includes(`$${tag}$`)) tag += "x";
  return `$${tag}$${text}$${tag}$`;
}

/** text[] literal */
function qArray(arr) {
  if (!Array.isArray(arr) || arr.length === 0) return "NULL";
  const items = arr.map((a) => `"${String(a).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`);
  return `'{${items.join(",")}}'::text[]`;
}

/** jsonb literal */
function qJson(value) {
  if (!value) return "NULL";
  return `${q(JSON.stringify(value))}::jsonb`;
}

const files = readdirSync(postsDir).filter((f) => f.endsWith(".md")).sort();

const rows = files.map((file) => {
  const raw = readFileSync(join(postsDir, file), "utf-8");
  const { data, content } = matter(raw);
  const slug = data.slug || file.replace(".md", "");

  return {
    file,
    slug,
    values: [
      q(data.title),
      q(slug),
      q(data.excerpt),
      q(content.trim()),
      q(data.category),
      q(data.author || "Bless Kimbi"),
      q(data.imageUrl),
      qArray(data.tags),
      qJson(data.faqs),
      q(data.seoTitle),
      q(data.metaDescription || data.description),
      q(data.focusKeyword),
      q(data.readTime),
      "'published'",
      data.date ? `'${new Date(data.date).toISOString()}'::timestamptz` : "now()",
    ],
  };
});

const columns = [
  "title", "slug", "excerpt", "content", "category", "author", "image_url",
  "tags", "faqs", "seo_title", "meta_description", "focus_keyword",
  "read_time", "status", "published_at",
];

const sql = `-- Blog posts moved from posts/*.md into the database, so they can be
-- written and edited from the dashboard instead of requiring a commit.
--
-- GENERATED by scripts/gen-posts-migration.mjs — re-run that rather than
-- hand-editing. Safe to run more than once: the insert is idempotent on slug.
--
-- Run in Supabase Dashboard → SQL Editor.

CREATE TABLE IF NOT EXISTS posts (
  id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  title            TEXT NOT NULL,
  slug             TEXT UNIQUE NOT NULL,
  excerpt          TEXT,
  content          TEXT NOT NULL,
  category         TEXT,
  author           TEXT DEFAULT 'Bless Kimbi',
  image_url        TEXT,
  tags             TEXT[],
  faqs             JSONB,
  seo_title        TEXT,
  meta_description TEXT,
  focus_keyword    TEXT,
  read_time        TEXT,
  status           TEXT NOT NULL DEFAULT 'draft'
                   CHECK (status IN ('draft', 'published')),
  published_at     TIMESTAMPTZ,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- The blog lists newest-first and looks posts up by slug.
CREATE INDEX IF NOT EXISTS posts_published_idx
  ON posts (status, published_at DESC);

-- Keep updated_at honest without the client having to remember.
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $fn$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$fn$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS posts_set_updated_at ON posts;
CREATE TRIGGER posts_set_updated_at
  BEFORE UPDATE ON posts
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ── Row-level security, matching the projects table ───────────────────────
ALTER TABLE posts ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can read published posts" ON posts;
CREATE POLICY "Public can read published posts" ON posts
  FOR SELECT TO anon
  USING (status = 'published');

DROP POLICY IF EXISTS "Authenticated can read all posts" ON posts;
CREATE POLICY "Authenticated can read all posts" ON posts
  FOR SELECT TO authenticated
  USING (true);

DROP POLICY IF EXISTS "Authenticated can insert posts" ON posts;
CREATE POLICY "Authenticated can insert posts" ON posts
  FOR INSERT TO authenticated
  WITH CHECK (true);

DROP POLICY IF EXISTS "Authenticated can update posts" ON posts;
CREATE POLICY "Authenticated can update posts" ON posts
  FOR UPDATE TO authenticated
  USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Authenticated can delete posts" ON posts;
CREATE POLICY "Authenticated can delete posts" ON posts
  FOR DELETE TO authenticated
  USING (true);

-- ── The ${rows.length} existing posts ───────────────────────────────────────────────
-- ON CONFLICT (slug) DO NOTHING, so re-running never duplicates or overwrites
-- anything you have since edited in the dashboard.

INSERT INTO posts (${columns.join(", ")}) VALUES
${rows.map((r) => `-- ${r.file}\n(${r.values.join(",\n ")})`).join(",\n\n")}
ON CONFLICT (slug) DO NOTHING;

-- ── Verify ────────────────────────────────────────────────────────────────
-- Expect ${rows.length} rows, every slug matching its old URL:
--
--   SELECT slug, status, published_at::date, length(content) AS chars
--   FROM posts ORDER BY published_at DESC;
`;

writeFileSync(outFile, sql, "utf-8");

console.log(`[gen-posts-migration] ${rows.length} posts -> ${outFile}`);
rows.forEach((r) => console.log(`  ${r.slug}`));
